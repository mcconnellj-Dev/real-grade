"""Share of reviews that mention each red-flag theme (pipeline/themes.json), from
Inside Airbnb review text in 8 markets. The extension flags a listing when its
loaded reviews mention a theme far more often than this baseline."""
import glob, json, os, re
import pandas as pd
import build_benchmarks as bb

ALL = json.load(open(os.path.join(os.path.dirname(__file__), "themes.json")))
NEG = ALL.pop("_negation")
THEMES = ALL
NEG_RE = re.compile(NEG["pattern"], re.I)


def mentions(text, pat):
    """True if any match of pat in text is not negated just before it."""
    for m in pat.finditer(text):
        if not NEG_RE.search(text[max(0, m.start() - NEG["window"]):m.start()]):
            return True
    return False


def main():
    pats = {k: re.compile(v["pattern"], re.I) for k, v in THEMES.items()}
    n = 0
    hits = {k: 0 for k in THEMES}
    for f in sorted(glob.glob(os.path.join(bb.RAW, "iab_rev_*.csv.gz"))):
        r = pd.read_csv(f, usecols=["date", "comments"]).dropna()
        r = r[r.date >= "2024-01-01"]  # recent reviews, like the ones a page shows
        n += len(r)
        for k, p in pats.items():
            hits[k] += int(sum(mentions(c, p) for c in r.comments if p.search(c)))
    base = {k: round(hits[k] / n, 5) for k in THEMES}
    for k in THEMES:
        print(f"{THEMES[k]['label']:18s} {base[k] * 100:6.2f}% of reviews")
    out = {"reviews": n, "negation": NEG, "themes": {k: {**THEMES[k], "baseline": base[k]} for k in THEMES}}
    js = "/* Generated by pipeline/review_baselines.py. Do not edit. */\nglobalThis.REAL_GRADE_THEMES = " + json.dumps(out) + ";\n"
    open(os.path.join(bb.EXT, "themes.js"), "w").write(js)
    print(f"reviews since 2024: {n:,}; wrote extension/data/themes.js")


if __name__ == "__main__":
    main()
