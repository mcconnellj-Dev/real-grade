"""Calibrate the your-search ranking against true market percentiles.

Live searches in 12 covered markets (data/raw/calib/<market>__<window>.json, first 4
result pages) give listings Airbnb chose to show. For each we know its true market
percentile from the benchmarks. Airbnb shows better-rated places first, so a
listing's rank within a search overstates how weak it is in the full market. We learn
G, the distribution of true market percentiles among search-shown listings, and map
a search rank q to G^-1(q). Each market is held out in turn to measure error against
the nearest-market fallback the extension used before."""
import glob, json, os
import numpy as np, pandas as pd
import build_benchmarks as bb
from fallback_test import miles

B = json.loads(open(os.path.join(bb.EXT, "benchmarks.js")).read().split("= ", 1)[1].rstrip(";\n"))
K = B["fit"]["overall"]["k"]
BLEND = 0.5  # weight on the calibrated search rank vs the nearest market (tested 0-1 in steps of .25)


def market_pct(rating, count, key):
    m = B["markets"][key]
    adj = (count * rating + K * m["prior"]["overall"]) / (count + K)
    return float(np.interp(adj, m["q"]["overall"], np.linspace(0, 1, 101)))


def load():
    rows = []
    for f in sorted(glob.glob(os.path.join(bb.RAW, "calib", "*.json"))):
        raw = open(f).read()
        d = json.loads(raw[raw.index("{"):raw.rindex("}") + 1])
        key, window = os.path.basename(f)[:-5].split("__")
        c = pd.DataFrame([x for x in d["cards"] if x["rating"] and x["count"]])
        mu = c.rating.mean()
        c["adj_search"] = (c["count"] * c.rating + K * mu) / (c["count"] + K)
        c["search_pct"] = c.adj_search.rank(pct=True, method="average") - 0.5 / len(c)
        c["truth"] = [market_pct(r, n, key) for r, n in zip(c.rating, c["count"])]
        c["market"], c["window"], c["search_mean"] = key, window, mu
        rows.append(c)
    return pd.concat(rows, ignore_index=True)


def main():
    d = load()
    print(f"{len(d)} rated listings from {d.groupby(['market', 'window']).ngroups} searches")
    print("\nmean true market percentile of what search shows, by market:")
    print((d.groupby("market").truth.mean() * 100).round(1).sort_values().to_string())
    grid = np.linspace(0, 1, 101)

    def nearest_pct(test, m):
        c0 = B["center"][m]
        near = min((k for k in B["marketKeys"] if k != m), key=lambda k: miles(c0, B["center"][k]))
        return np.array([market_pct(r, n, near) for r, n in zip(test.rating, test["count"])]), near

    def score(train, test, m):
        calibrated = np.interp(test.search_pct, grid, np.quantile(train.truth, grid))
        nearest, near = nearest_pct(test, m)
        blend = BLEND * calibrated + (1 - BLEND) * nearest
        err = lambda p: np.abs(p - test.truth).mean() * 100
        return {"market": m, "n": len(test), "raw_search_rank": err(test.search_pct), "nearest_market": err(nearest),
                "calibrated_search": err(calibrated), "blend": err(blend), "nearest_name": B["markets"][near]["name"]}

    # 1) hold out each market (both date windows)
    r = pd.DataFrame([score(d[d.market != m], d[d.market == m], m) for m in sorted(d.market.unique())]).set_index("market")
    cols = ["raw_search_rank", "nearest_market", "calibrated_search", "blend"]
    print("\nheld-out market error, percentile points (lower is better):")
    print(r.round(1).to_string())
    print("mean:", r[cols].mean().round(2).to_dict())
    # 2) learn from January searches only, test on June searches of other markets
    if d.window.nunique() > 1:
        t = pd.DataFrame([score(d[(d.window == "jan") & (d.market != m)], d[(d.window == "jun") & (d.market == m)], m)
                          for m in sorted(d.market.unique()) if ((d.window == "jun") & (d.market == m)).any()])
        print("\ntrained on January, tested on June (held-out market):", t[cols].mean().round(2).to_dict())
    G = np.quantile(d.truth, grid)
    out = {"source": f"{len(d)} listings from {d.groupby(['market', 'window']).ngroups} live searches in 12 markets",
           "q": [round(float(v), 4) for v in G], "minRated": 20, "blend": BLEND}
    json.dump(out, open(os.path.join(bb.OUT, "search_calibration.json"), "w"))
    js = "/* Generated by pipeline/search_calibration.py. Do not edit. */\nglobalThis.REAL_GRADE_CALIBRATION = " + json.dumps(out) + ";\n"
    open(os.path.join(bb.EXT, "calibration.js"), "w").write(js)
    print("\nwrote extension/data/calibration.js")


if __name__ == "__main__":
    main()
